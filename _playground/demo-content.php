foreach ( $items as $item ) {
	$post_id = wp_insert_post(
		array(
			'post_type'    => 'news',
			'post_title'   => $item['title'],
			'post_content' => $item['body'],
			'post_status'  => 'publish',
			'post_date'    => $item['date'],
		)
	);

	if ( ! $post_id || is_wp_error( $post_id ) ) {
		continue;
	}

	$term = term_exists( $item['cat'], 'news_cat' );
	if ( ! $term ) {
		$term = wp_insert_term( $item['cat'], 'news_cat' );
	}
	if ( ! is_wp_error( $term ) ) {
		wp_set_object_terms( $post_id, (int) $term['term_id'], 'news_cat' );
	}
}

